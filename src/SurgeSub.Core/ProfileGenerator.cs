using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace SurgeSub.Core;

public static partial class ProfileGenerator
{
    public static string Hash(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));

    public static GeneratedProfile Generate(ClientBundle bundle, ClientSettings settings, IReadOnlyList<AdapterInfo> adapters, string generationsDirectory, bool localProxyAvailable = true)
    {
        Validation.Settings(settings);
        if (bundle.SchemaVersion != 1 || bundle.Bindings is null || bundle.Sections is null || bundle.NodeResources is null
            || bundle.RefreshIntervalSeconds is < 60 or > 86400 || bundle.NodeResources.Length > 256)
            throw new ClientException("服务器配置包版本或结构不受支持。");
        var home = Validation.Device(Validation.Resolve(settings.Home!, adapters));
        var other = Validation.Device(Validation.Resolve(settings.Other!, adapters));
        if (home == other && home != Validation.MissingDevice) throw new ClientException("两个出口解析到了同一张网卡，请重新选择。");
        var bindings = bundle.Bindings;
        foreach (var n in new[] { bindings.HomePolicy, bindings.OtherPolicy, bindings.LocalProxyPolicy }) Validation.Name(n);
        if (new[] { bindings.HomePolicy, bindings.OtherPolicy, bindings.LocalProxyPolicy }.Distinct().Count() != 3)
            throw new ClientException("服务器出口名称重复。");
        var process = Validation.ProcessPath(settings.ProxyApplication);
        var digest = Hash(JsonSerializer.Serialize(bundle, ClientJson.Default.ClientBundle) + home + "\n" + other
            + "\n" + settings.ProxyPort + "\n" + process + "\n" + localProxyAvailable);
        var nodeFiles = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var resource in bundle.NodeResources)
        {
            if (!ResourceId().IsMatch(resource.Id) || resource.Policies.Length == 0 || resource.Policies.Length > 10000
                || !nodeFiles.TryAdd(resource.Id, string.Join('\n', resource.Policies.Select(p => BindNode(p, other))) + "\n"))
                throw new ClientException("服务器节点资源为空、重复或标识无效。");
        }
        if (nodeFiles.Count == 0) throw new ClientException("服务器未返回节点资源。");
        var output = new StringBuilder("# Generated by SurgeSub. Update through SurgeSub.\n");
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var requiredAliases = new HashSet<string>(StringComparer.Ordinal);
        foreach (var section in bundle.Sections)
        {
            if (!SectionName().IsMatch(section.Name) || !seen.Add(section.Name)) throw new ClientException("服务器配置段无效或重复。");
            output.Append('\n').Append('[').Append(section.Name).AppendLine("]");
            if (section.Name == "Rule")
                output.Append("PROCESS-NAME,").Append(process).Append(',').AppendLine(bindings.OtherPolicy);
            foreach (var raw in section.Lines)
            {
                var line = raw.Trim();
                if (line.Contains('\n') || line.Contains('\r') || line.StartsWith("#!", StringComparison.Ordinal) || line.StartsWith('['))
                    throw new ClientException("服务器配置包含不允许的嵌套指令。");
                if (section.Name == "Proxy")
                {
                    var (name, value) = Assignment(line);
                    if (name == bindings.LocalProxyPolicy) throw new ClientException("本地代理必须由本机配置。");
                    if (name == bindings.HomePolicy || name == bindings.OtherPolicy)
                    {
                        if (!requiredAliases.Add(name) || value.Split(',')[0].Trim() != "direct") throw new ClientException("出口策略必须是唯一定义的 direct。");
                        line = Bind(line, name == bindings.HomePolicy ? home : other);
                    }
                    else if (InterfaceField().IsMatch(value)) throw new ClientException("存在未声明出口角色的网卡绑定。");
                }
                if (section.Name == "Proxy Group") line = BindResource(line, nodeFiles, Path.Combine(generationsDirectory, digest));
                if (line.Contains("surgesub-resource:", StringComparison.Ordinal)) throw new ClientException("存在未解析的节点资源引用。");
                output.AppendLine(line);
            }
            if (section.Name == "Proxy")
            {
                output.Append(bindings.LocalProxyPolicy);
                if (localProxyAvailable) output.Append(" = socks5, 127.0.0.1, ").Append(settings.ProxyPort).AppendLine(", udp-relay=true");
                else output.AppendLine(" = reject");
            }
        }
        if (requiredAliases.Count != 2 || !new[] { "General", "Proxy", "Proxy Group", "Rule", "Host" }.All(seen.Contains))
            throw new ClientException("服务器配置缺少必要的配置段或出口。");
        return new(output.ToString(), nodeFiles, digest, home, other);
    }

    public static (string Name, string Value) Assignment(string line)
    {
        var p = line.IndexOf('=');
        if (p < 1 || p == line.Length - 1) throw new ClientException("无效的策略定义。");
        var name = line[..p].Trim(); Validation.Name(name);
        return (name, line[(p + 1)..].Trim());
    }

    private static string BindNode(string line, string device)
    {
        var (_, value) = Assignment(line);
        if (line.Contains('\n') || line.Contains('\r') || !value.StartsWith("ss,", StringComparison.Ordinal)
            || value.Split(',').Any(f => f.Trim().StartsWith("underlying-proxy=", StringComparison.Ordinal)))
            throw new ClientException("节点类型不受支持或包含代理链。");
        return Bind(line, device);
    }
    private static string Bind(string line, string device)
    {
        var (name, value) = Assignment(line);
        var fields = value.Split(',', StringSplitOptions.TrimEntries)
            .Where(f => f.Split('=')[0].Trim() is not ("interface" or "allow-other-interface"));
        return name + " = " + string.Join(", ", fields) + ", interface=" + device + ", allow-other-interface=false";
    }
    private static string BindResource(string line, Dictionary<string, string> files, string directory)
    {
        // Server-generated group lines have an unquoted resource marker. Preserve every other parameter.
        return ResourceReference().Replace(line, m =>
        {
            var id = m.Groups[1].Value;
            if (!files.ContainsKey(id)) throw new ClientException("分组引用了不存在的节点资源。");
            return "policy-path=\"" + Path.Combine(directory, id).Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        });
    }
    [GeneratedRegex("^(?:all|[a-f0-9]{64})\\.conf$")]
    private static partial Regex ResourceId();
    [GeneratedRegex("^(?:General|Proxy|Proxy Group|Rule|Host|Script|Ruleset [^\\r\\n\\[\\]]+)$")]
    private static partial Regex SectionName();
    [GeneratedRegex("(?:^|,)\\s*interface\\s*=")]
    private static partial Regex InterfaceField();
    [GeneratedRegex("policy-path=surgesub-resource:([a-z0-9]+\\.conf)")]
    private static partial Regex ResourceReference();
}
